def make_demo_project(parent: str) -> str:
    """在 parent 底下建立範例專案，回傳專案資料夾路徑。已存在的檔案會被覆寫。"""
    root = os.path.join(parent, PROJECT)
    for sub, name, stamp in FILES:
        folder = os.path.join(root, sub) if sub else root
        os.makedirs(folder, exist_ok=True)
        path = os.path.join(folder, name)
        with open(path, "wb") as f:
            f.write(b"WingLightFinder demo file\n" * (1 + len(name) * 40))
        t = time.mktime(datetime.strptime(stamp, "%Y-%m-%d %H:%M").timetuple())
        os.utime(path, (t, t))
    return root
